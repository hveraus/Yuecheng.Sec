import assert from 'node:assert/strict';
import {metrics,dimensions,normalize,calculate,median,ratio,grade,demoHistory} from '../dist/safety-index.js';
assert.equal(metrics.length,15);assert.equal(new Set(metrics.map(m=>m.id)).size,15);
assert.equal(dimensions.reduce((s,d)=>s+d[2],0),1);
assert.equal(normalize(97,[90,97,99.5]),70);assert.equal(normalize(93.5,[90,97,99.5]),35);
assert.equal(normalize(7,[12,10,2]),81.25);assert.equal(normalize(100,[48,12,2]),0);
assert.equal(normalize(null,[0,5,10]),null);assert.equal(normalize(NaN,[0,5,10]),null);
assert.equal(median([1,2,3,999]),2.5);assert.equal(median([]),null);assert.equal(ratio(0,0),null);
assert.deepEqual([54,55,69,70,84,85,null].map(grade),['预警','关注','关注','正常','正常','良好','数据不足']);
const perfect=Object.fromEntries(metrics.map(m=>[m.id,m.thresholds[2]]));
assert.equal(calculate(perfect).score,100);
const missing=calculate({...perfect,online:null});assert.equal(missing.score,100);assert.equal(missing.groups[0].incomplete,true);
assert.equal(calculate({...perfect,online:null,repair:null}).score,null);
assert.equal(calculate({}).score,null);
const poor=calculate(Object.fromEntries(metrics.map(m=>[m.id,m.thresholds[0]])));assert.equal(poor.score,0);
assert.equal(Math.round(poor.drivers.reduce((s,m)=>s+m.loss,0)),100);
const history=demoHistory('pressure');assert.equal(history.length,7);assert(history[6].score<55);assert(history[6].score<history[5].score);
assert.equal(demoHistory('missing')[6].incomplete,true);
console.log('PASS: 15 metrics, interpolation, grades, missing data, weighting, loss contributions and scenario trends');
